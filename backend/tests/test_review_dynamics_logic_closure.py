def test_ema5_exact_values() -> None:
    """EMA5 on ready positions 10,20,30,40,50,60.  alpha = 2/6 = 1/3.
    Hand recursion (state s): s1=10; s2=40/3; s3=170/9; s4=... ; s5 (5th valid,
    first ready) and s6 hand-computed below."""
    values = [10.0, 20.0, 30.0, 40.0, 50.0, 60.0]
    pos = _ready_position_series(values)
    chain = compute_historical_dynamics_series(pos)
    ema5 = chain["ema5"]

    # Warmup: first 4 valid inputs -> insufficient_history (value None).
    for i in range(4):
        assert ema5[i]["status"] == STATUS_INSUFFICIENT
        assert ema5[i]["value"] is None
    # 5th valid -> first ready.
    assert ema5[4]["status"] == STATUS_READY
    # Exact state after the recursion:
    #   s1 = 10
    #   s2 = (20 + 2*10)/3 = 40/3 = 13.3333
    #   s3 = (30 + 2*(40/3))/3 = (30 + 80/3)/3 = (90+80)/9 = 170/9 = 18.8889
    #   s4 = (40 + 2*(170/9))/3 = (360/9 + 340/9)/3 = (700/9)/3 = 700/27 = 25.9259
    #   s5 = (50 + 2*(700/27))/3 = (1350/27 + 1400/27)/3 = (2750/27)/3 = 2750/81 = 33.9506
    #   s6 = (60 + 2*(2750/81))/3 = (4860/81 + 5500/81)/3 = (10360/81)/3 = 10360/243 = 42.6337
    assert ema5[4]["value"] == pytest.approx(2750 / 81, abs=1e-9)
    assert ema5[5]["value"] == pytest.approx(10360 / 243, abs=1e-9)
    # valid_count reflects the number of valid inputs consumed.
    assert ema5[4]["valid_count"] == 5
    assert ema5[5]["valid_count"] == 6


def test_ema20_warmup_at_20th_valid() -> None:
    """EMA20: 19th valid input -> insufficient_history; 20th valid -> first ready.
    alpha = 2/21.  State stays at seed 10 for constant input; the first ready value
    equals the seed (10.0) because every input is identical."""
    values = [10.0] * 22
    pos = _ready_position_series(values)
    chain = compute_historical_dynamics_series(pos)
    ema20 = chain["ema20"]
    assert ema20[18]["status"] == STATUS_INSUFFICIENT  # 19th valid
    assert ema20[18]["value"] is None
    assert ema20[19]["status"] == STATUS_READY  # 20th valid
    # Constant input -> EMA stays at the seed value.
    assert ema20[19]["value"] == pytest.approx(10.0, abs=1e-9)
    assert ema20[19]["valid_count"] == 20


def test_ema20_exact_jump_blend() -> None:
    """EMA20 exact blend after 20 identical seeds then one jump:
    state = (2/21)*jump + (19/21)*seed."""
    values = [10.0] * 20 + [25.0]
    pos = _ready_position_series(values)
    chain = compute_historical_dynamics_series(pos)
    ema20 = chain["ema20"]
    assert ema20[20]["status"] == STATUS_READY
    assert ema20[20]["value"] == pytest.approx((2 / 21) * 25.0 + (19 / 21) * 10.0, abs=1e-9)


