def _full_ready_position_series(count: int, base: float = 10.0) -> list[dict[str, Any]]:
    days = _trading_days(date(2026, 1, 5), count)
    return [_position_fact(d, base + (i % 7), STATUS_READY) for i, d in enumerate(days)]


def test_pos3_120d_rolling_boundary_t125_unaffected_by_rolled_out() -> None:
    """POS-3: on a >120-day ready series, T at index 124 uses only the latest 120
    candidate slots before it.  Mutating observations 1..4 (already rolled out of
    the 120-window) must leave Position(124) bit-identical."""
    count = 126  # indices 0..125; T125 = index 124
    base = _full_ready_position_series(count)
    t = 124
    before = compute_position_series_from_primitive_series(
        _to_primitive_series(base)
    )[t]

    mutated = list(base)
    # T125 (index 124) baseline = latest 120 slots before it = indices [4, 123].
    # Indices 0..3 have rolled out of the window, so mutating them (first 4)
    # must leave T125 bit-identical.
    for i in (0, 1, 2, 3):
        mutated[i] = _position_fact(date.fromisoformat(base[i]["trade_date"]), 999.0, STATUS_READY)
    after = compute_position_series_from_primitive_series(_to_primitive_series(mutated))[t]
    assert after == before


def _to_primitive_series(position_series: list[dict[str, Any]]) -> dict[str, Any]:
    """Wrap Position facts into the formal PrimitiveSeries shape
    (``primitives[key]`` = ``{"key", "points"}`` with per-point
    ``{"trade_date", "readiness", "value", "available"}``) that
    ``compute_position_series_from_primitive_series`` consumes.  ``readiness`` maps
    from the Position status so the Position window / percentile logic sees the
    same availability the canonical chain would."""
    return {
        "key": DYNAMICS_PHASE_PRIMITIVE_KEY,
        "points": [
            {
                "trade_date": f["trade_date"],
                "readiness": (
                    "ready"
                    if f["status"] == STATUS_READY
                    else "unavailable"
                ),
                "value": f["position"],
                "available": f["position"] is not None,
            }
            for f in position_series
        ],
    }


