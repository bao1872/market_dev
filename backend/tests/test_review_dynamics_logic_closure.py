def _real_series_item(
    trade_date: date,
    ret: float,
    amount: float = 1e6,
) -> dict[str, Any]:
    member = MemberObservation(
        member_id="m1",
        price_candidate=True,
        return_1d=ret,
        amount=amount,
        trend=Direction.UP,
        swing=Direction.UP,
        internal=Direction.UP,
        momentum=MomentumDirection.EXPANDING,
        regime_strength=0.5,
        vol_ratio20=1.0,
        vol_ratio200=2.0,
    )
    payload = compute_scope_observation(
        scope_type="industry",
        scope_key="electronics",
        trade_date=trade_date,
        pit_member_ids=["m1"],
        members=[member],
        event_coverage_member_ids=None,
    )
    return {"trade_date": trade_date.isoformat(), "observation": payload}


def test_os1_continuous_timeline_order_preserved_no_sort_no_dedupe() -> None:
    """OS-1: a continuous, non-monotonic value timeline flows through the Builder
    with its date order preserved — no silent sort, no dedupe, no re-interpretation
    of the L1 payload."""
    days = _trading_days(date(2026, 1, 5), 8)
    values = [0.01, 0.03, -0.02, 0.05, 0.00, 0.02, -0.01, 0.04]
    raw = [
        _real_series_item(d, ret=v)
        for d, v in zip(days, values, strict=True)
    ]
    obs_series = build_observation_series(
        scope_type="industry",
        scope_key="electronics",
        from_date=days[0],
        to_date=days[-1],
        trading_dates=days,
        snapshot_series=[
            {"trade_date": d.isoformat(), "readiness": "ready", "payload": p["observation"]}
            for d, p in zip(days, raw, strict=True)
        ],
    )
    ew = obs_series["primitives"][DYNAMICS_PHASE_PRIMITIVE_KEY]
    ew_points = ew["points"]
    # Date axis == input axis (ascending, full length, no compression / dedupe).
    assert [p["trade_date"] for p in ew_points] == [d.isoformat() for d in days]
    assert len(ew_points) == len(days)
    # EW primitive equals the equal-weighted member return at each day.
    for p, v in zip(ew_points, values, strict=True):
        assert p["value"] == pytest.approx(v)


