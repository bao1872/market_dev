def test_up_day_positive_contributor_leads() -> None:
    # EW>0 (up).  A: amount_share=0.5 (amount 50/100), return +0.04 -> contrib
    # 0.02; B: 0.5 * -0.02 = -0.01 (contrarian).  leader set = {A}.
    snap = _snap("2026-01-05", 0.03, [_m("a", return_1d=0.04, amount=50.0),
                                      _m("b", return_1d=-0.02, amount=50.0)])
    assert snap.status == "ready"
    assert snap.direction == 1
    assert snap.leader_ids == ("a",)
    assert snap.leader_set[0].aligned_score == pytest.approx(0.02)


def test_down_day_negative_contributor_leads() -> None:
    # EW<0 (down).  A contributes -0.02 (down-driver), B +0.01 (contrarian).
    snap = _snap("2026-01-05", -0.03, [_m("a", return_1d=-0.04, amount=50.0),
                                       _m("b", return_1d=0.02, amount=50.0)])
    assert snap.status == "ready"
    assert snap.direction == -1
    assert snap.leader_ids == ("a",)          # down-driver is the leader
    assert snap.leader_set[0].aligned_score == pytest.approx(0.02)


def test_contrarian_excluded() -> None:
    # Down scope; only B has a positive raw return (contrarian) -> aligned<0,
    # excluded from leader set -> legitimate empty.
    snap = _snap("2026-01-05", -0.05, [_m("b", return_1d=0.02, amount=100.0)])
    assert snap.status == "ready"
    assert snap.direction == -1
    assert snap.leader_set == ()


def test_fifty_percent_minimal_prefix() -> None:
    # amounts a=b=c=d=25 -> share 0.25 each.
    # returns: a=0.08 b=0.04 c=0.02 d=0.01
    # aligned (up): a=.02 b=.01 c=.005 d=.0025 ; total=.0375
    # 50% = .01875 -> {a,b} (a=.02 alone < .01875? .02 >= .01875 -> actually {a}).
    # Recompute: cumulative a=.02 >= .01875 -> leader set = {a} only.
    members = [
        _m("a", return_1d=0.08, amount=25.0),
        _m("b", return_1d=0.04, amount=25.0),
        _m("c", return_1d=0.02, amount=25.0),
        _m("d", return_1d=0.01, amount=25.0),
    ]
    snap = _snap("2026-01-05", 0.06, members)
    assert snap.status == "ready"
    # a alone explains 0.02/0.0375 = 53% >= 50% -> leader set = {a}.
    assert snap.leader_ids == ("a",)


def test_threshold_exactly_fifty_percent() -> None:
    # Two members each 0.5 share.  a return 0.04 -> .02; b return 0.02 -> .01.
    # total .03; 50% = .015.  cumulative a=.02 >= .015 -> leader set = {a}.
    members = [
        _m("a", return_1d=0.04, amount=50.0),
        _m("b", return_1d=0.02, amount=50.0),
    ]
    snap = _snap("2026-01-05", 0.03, members)
    assert snap.leader_ids == ("a",)
    assert snap.status == "ready"


def test_tie_member_id_asc() -> None:
    # Equal contributions -> deterministic member_id ASC.
    # amounts a=100 b=100 -> total 200 -> shares 0.5 each.
    # a return 0.04 -> .02; b return 0.04 -> .02 (tie).  Up scope.
    members = [_m("b", return_1d=0.04, amount=100.0), _m("a", return_1d=0.04, amount=100.0)]
    snap = _snap("2026-01-05", 0.04, members)
    assert snap.status == "ready"
    # Tie -> member_id ASC.  a and b both contribute 0.02; total 0.04, 50%=0.02,
    # so the minimal prefix is {a} (a alone reaches 50%); a before b.
    assert snap.leader_ids[0] == "a"


