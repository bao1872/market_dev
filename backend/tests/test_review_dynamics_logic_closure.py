def _returns(count: int) -> list[float]:
    return [0.012 * math.sin(i / 12) + 0.0015 * ((i * 7) % 5 - 2) for i in range(count)]


def test_composition_equivalence_over_real_payload() -> None:
    """Composition equivalence: ``compute_scope_dynamics_analysis`` (formal) equals
    calling the canonical owners in sequence over a real canonical L1 payload."""
    days = _trading_days(date(2026, 1, 5), 130)
    raw = [_real_series_item(d, ret=r) for d, r in zip(days, _returns(130), strict=True)]
    obs_series = build_observation_series(
        scope_type="industry",
        scope_key="electronics",
        from_date=days[0],
        to_date=days[-1],
        trading_dates=days,
        snapshot_series=[
            {"trade_date": d.isoformat(), "readiness": "ready", "payload": p["observation"]}
            for d, p in zip(days, raw, strict=True)
        ],
    )

    composed = compute_scope_dynamics_analysis(obs_series)

    ew = obs_series["primitives"][DYNAMICS_PHASE_PRIMITIVE_KEY]
    pos = compute_position_series_from_primitive_series(ew)
    hd = compute_historical_dynamics_series(pos)
    ph = compute_dynamics_phase_series(hd)

    assert composed["historical_dynamics"] == hd
    assert composed["dynamics_phase"] == ph
    assert composed["primitive_key"] == DYNAMICS_PHASE_PRIMITIVE_KEY
