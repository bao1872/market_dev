def _trading_days(start: date, count: int) -> list[date]:
    """Return ``count`` ascending weekdays starting at ``start``."""
    out: list[date] = []
    d = start
    while len(out) < count:
        if d.weekday() < 5:
            out.append(d)
        d += timedelta(days=1)
    return out


def _position_fact(
    td: date,
    position: float | None,
    status: str,
) -> dict[str, Any]:
    """A Position fact in the exact shape produced by ``compute_position_series``."""
    return {
        "primitive_key": "equal_weight_return",
        "trade_date": td.isoformat(),
        "value": position,
        "position": position,
        "history": {
            "window_size": 120,
            "minimum_valid_history": 60,
            "candidate_count": 60,
            "valid_count": 60,
        },
        "status": status,
    }


def _ready_position_series(values: list[float]) -> list[dict[str, Any]]:
    days = _trading_days(date(2026, 1, 5), len(values))
    return [_position_fact(d, v, STATUS_READY) for d, v in zip(days, values, strict=True)]


