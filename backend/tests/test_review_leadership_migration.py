"""Stage 4B — Leadership Migration formal owner Golden tests.

Locks the frozen PRD §7.10 "Leadership Migration Numerical Contract (FROZEN)"
against the production owner (``build_leadership_snapshot`` +
``compute_leadership_migration``).  Expected values are hand-fixed from the
contract math, NOT generated by the owner under test.

Covers:
  1. up-day leader           2. down-day leader
  3. contrarian excluded     4. 50% minimal prefix
  5. threshold == 50%        6. tie -> member_id ASC
  7. single member           8. EW None
  9. EW zero                 10. valid empty leader set
  11. full-stable            12. full-replacement
  13. partial overlap        14. leader-set expansion
  15. leader-set contraction 16. previous snapshot unavailable
  17. current snapshot unavailable
  18. empty leader-set transition unavailable
  19. deterministic repeat   20. future leak = 0

The migration owner consumes pre-computed ``LeadershipContributionFacts`` (from
the single Stage-1 owner ``compute_member_leadership_contributions``) — it never
re-derives amount_share or contribution.
"""

from __future__ import annotations

from datetime import date

import pytest

from app.domain.first_pyramid_semantics import Direction, MomentumDirection
from app.domain.review.analysis.leadership_contribution import (
    compute_member_leadership_contributions,
)
from app.domain.review.analysis.leadership_migration import (
    LEADERSHIP_COVERAGE,
    build_leadership_snapshot,
    compute_leadership_migration,
)
from app.domain.review.scope_observation import MemberObservation

pytestmark = pytest.mark.pure_unit


def _m(
    mid: str,
    *,
    return_1d: float | None = None,
    amount: float | None = 100.0,
) -> MemberObservation:
    return MemberObservation(
        member_id=mid,
        price_candidate=True,
        return_1d=return_1d,
        amount=amount,
        trend=Direction.UP,
        swing=Direction.UP,
        internal=Direction.UP,
        momentum=MomentumDirection.EXPANDING,
    )


def _facts(members: list[MemberObservation]):
    return compute_member_leadership_contributions(members)


def _snap(day: str, ew: float | None, members: list[MemberObservation]):
    return build_leadership_snapshot(
        trade_date=day, ew_return=ew, contribution_facts=_facts(members)
    )


